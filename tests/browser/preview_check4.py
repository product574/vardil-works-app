import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, "fixtures") + os.sep
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from playwright.sync_api import sync_playwright
errs=[]; reqs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ.get("CHROME", "/usr/bin/google-chrome"), args=["--no-sandbox"])
    page=b.new_page(viewport={"width":1440,"height":900})
    page.on("console", lambda m: errs.append(f"{m.type}: {m.text}") if m.type=="error" else None)
    page.on("pageerror", lambda e: errs.append(f"pageerror: {e}"))
    page.on("request", lambda r: reqs.append(r.url) if not r.url.startswith(("file:","data:","blob:")) else None)
    page.goto("file://" + REPO + "/dist-preview/index.html"); page.wait_for_selector("#username")
    page.fill("#username","demo"); page.fill("#password","demo"); page.keyboard.press("Enter")
    page.get_by_role("button", name="Managing director").click(); page.wait_for_selector("text=AI overview")
    bar=page.locator("nav[aria-label=Departments]"); side=page.locator("nav[aria-label$=screens]:visible")
    bar.get_by_role("link", name="Schedule").click(); page.wait_for_selector("text=Not placed")
    blk=page.locator("section", has=page.get_by_role("link", name="C719 St Finian's Church"))
    blk.get_by_label("Trade to add to C719").select_option("Scaffolder"); page.wait_for_timeout(150)
    blk.get_by_label("Person to add to C719").select_option(index=1); page.wait_for_timeout(150)
    blk.get_by_role("button", name="Plan for the week").click(); page.wait_for_timeout(300)
    blk.get_by_role("button", name="Adrian Stoica: contact details and options").click(); page.wait_for_selector("dialog[open] a[href^='tel:']")
    page.locator("dialog[open]").get_by_role("button", name="Take off C719").click(); page.wait_for_timeout(300)
    bar.get_by_role("link", name="People").click(); page.wait_for_selector("text=marked for today")
    side.get_by_role("link", name="Training tickets").click(); page.wait_for_selector("text=On paper file")
    page.locator("tbody tr").first.get_by_role("button", name="Record renewal").click()
    d=page.locator("dialog[open]"); d.get_by_label("Choose a proof from this device").set_input_files(FIX + "card.png"); page.wait_for_timeout(500)
    d.get_by_role("button", name="Save renewal").click(); page.wait_for_timeout(300)
    bar.get_by_role("link", name="Projects").click(); page.wait_for_selector("table")
    page.locator("tbody tr", has_text="C721").click(); page.wait_for_selector("text=Key facts")
    page.get_by_role("tab", name="Photos").click(); page.get_by_role("button", name="Add a photo").click()
    d=page.locator("dialog[open]"); d.get_by_label("Choose a photo from this device").set_input_files(FIX + "site-photo.jpg"); page.wait_for_timeout(700)
    d.get_by_label("Caption").fill("East gable, slating"); d.get_by_role("button", name="Add photo").click(); page.wait_for_timeout(400)
    assert page.locator("main ul li img").count()==1
    page.get_by_role("button", name="Account menu").click(); page.get_by_role("menuitem", name="Settings").click(); page.wait_for_selector("text=What they can do")
    page.get_by_role("tab", name="By person").click(); page.wait_for_selector("text=Sign in as")
    page.get_by_role("list", name="Office and management staff").get_by_role("button", name="Darragh Lenihan").click(); page.wait_for_timeout(200)
    page.get_by_role("checkbox", name="Darragh Lenihan: Plan the week ahead").click()
    page.get_by_role("button", name="Sign in as Darragh to check").click(); page.wait_for_selector("text=marked for today")
    assert "Darragh Lenihan" in page.locator("header").first.inner_text()
    size=page.evaluate("localStorage.getItem('cod.data').length")
    print("preview file: not placed list, trade picker, person box, take off, proof, photo, access by person, sign in as a person all work")
    print("saved demo data with one photo and one proof:", round(size/1024), "thousand characters of roughly 5,000 allowed")
    print("outside requests:", reqs, "| errors:", errs)
    b.close()
